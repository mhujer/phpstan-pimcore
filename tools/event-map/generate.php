<?php

declare(strict_types=1);

use PhpParser\Node\Scalar\String_;
use PhpParser\Node\Stmt\Class_;
use PhpParser\Node\Stmt\ClassConst;
use PhpParser\NodeFinder;
use PhpParser\ParserFactory;

require __DIR__ . '/../../vendor/autoload.php';

$parser = (new ParserFactory())->createForNewestSupportedVersion();
$finder = new NodeFinder();
$map = [];
foreach (['12.3', '2026'] as $line) {
    $directory = __DIR__ . '/../fixture-generator/vendor-' . $line . '/pimcore/pimcore';
    if (!is_dir($directory)) {
        throw new RuntimeException('Missing fixture dependency directory: ' . $directory);
    }
    foreach (new RecursiveIteratorIterator(new RecursiveDirectoryIterator($directory)) as $file) {
        if (!$file->isFile() || !str_ends_with($file->getFilename(), 'Events.php')) {
            continue;
        }
        $nodes = $parser->parse(file_get_contents($file->getPathname()));
        foreach ($finder->findInstanceOf($nodes, Class_::class) as $class) {
            if ($class->name === null || !str_ends_with($class->name->toString(), 'Events')) {
                continue;
            }
            foreach ($class->stmts as $constant) {
                if (!$constant instanceof ClassConst || !preg_match('/@Event\("([^"\r\n]+)"\)/', $constant->getDocComment()?->getText() ?? '', $match)) {
                    continue;
                }
                foreach ($constant->consts as $value) {
                    if (!$value->value instanceof String_) {
                        continue;
                    }
                    $event = $value->value->value;
                    $eventClass = ltrim($match[1], '\\');
                    if (isset($map[$event]) && $map[$event] !== $eventClass) {
                        throw new RuntimeException('Conflicting event classes for ' . $event);
                    }
                    $map[$event] = $eventClass;
                }
            }
        }
    }
}
$map = array_replace($map, require __DIR__ . '/corrections.php');
ksort($map);
$entries = [];
foreach ($map as $event => $eventClass) {
    $entries[] = '        ' . var_export($event, true) . ' => ' . var_export($eventClass, true) . ',';
}
file_put_contents(__DIR__ . '/../../src/Rules/EventMap.php', "<?php\n\ndeclare(strict_types=1);\n\nnamespace Mhujer\\PHPStan\\Pimcore\\Rules;\n\n// Generated by tools/event-map/generate.php. Event names and class names only.\nfinal class EventMap\n{\n    public const array EVENTS = [\n" . implode("\n", $entries) . "\n    ];\n}\n");
echo count($map), " event names written.\n";
